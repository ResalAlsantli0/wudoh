import json
import re
from typing import TypedDict

from dotenv import load_dotenv
from langchain_openai import ChatOpenAI
from langgraph.graph import END, START, StateGraph


# =====================================================
# LOAD ENVIRONMENT
# =====================================================

load_dotenv()


# =====================================================
# STATE
# =====================================================

class PolicyState(TypedDict):
    product_name: str
    policy_text: str
    result: dict


# =====================================================
# OPENAI MODEL
# =====================================================

model = ChatOpenAI(
    model="gpt-4o-mini",
    temperature=0
)


# =====================================================
# POLICY ANALYZER
# =====================================================

def analyze_policy(state: PolicyState):

    product_name = state["product_name"]
    policy_text = state["policy_text"]

    prompt = f"""
أنت محلل متخصص في سياسات الاسترجاع والاستبدال
للمتاجر الإلكترونية.

مهمتك الوحيدة هي استخراج:

1. مدة الاسترجاع.
2. مدة الاستبدال.

يجب أن تكون النتيجة مرتبطة بالمنتج المحدد فقط.

==================================================
اسم المنتج
==================================================

{product_name}

==================================================
نص سياسة المتجر
==================================================

{policy_text}

==================================================
قواعد التحليل
==================================================

1. اقرأ اسم المنتج بدقة.

2. حدّد أولاً نوع المنتج أو فئته من اسمه
   إذا كان ذلك واضحاً.

3. ابحث أولاً عن السياسة الخاصة بالمنتج
   أو الفئة التي ينتمي إليها.

4. إذا لم توجد سياسة خاصة بالمنتج أو فئته،
   استخدم السياسة العامة فقط إذا كانت تنطبق عليه.

5. ممنوع منعاً باتاً اختراع أو استنتاج
   أي عدد أيام غير مذكور صراحة
   في نص سياسة المتجر.

6. أي مدة تظهر في النتيجة
   يجب أن تكون مبنية على مدة موجودة
   فعلياً داخل نص السياسة المرسل أعلاه.

7. لا تستخدم أي أرقام من الأمثلة التوضيحية
   كإجابة للمنتج الحالي.

8. إذا كان النص يحتوي على مدد مختلفة
   لفئات مختلفة:
   - حدّد فئة المنتج أولاً.
   - استخدم فقط المدة المرتبطة بهذه الفئة.
   - لا تستخدم مدة تخص فئة أخرى.

9. مثال على تصنيف الفئات:
   - خلخال، سوار، عقد، خاتم، أقراط = إكسسوارات.
   - ساعة = ساعات.
   - فستان = فساتين.
   - iPhone، هاتف، لابتوب، سماعة، راوتر = إلكترونيات.
   - عطر، برفيوم = عطور.
   استخدم هذا فقط لفهم الفئة،
   وليس لاختراع سياسة غير موجودة في النص.

10. إذا كان المنتج مستثنى بشكل صريح وقاطع
    من الاسترجاع أو الاستبدال:
    أرجع:
    "غير متاح — المنتج مستثنى"

11. إذا كان الاستثناء يعتمد على حالة أو صفة معينة
    مثل:
    - مفتوح
    - مستخدم
    - بدون تاغ
    - تالف
    - بدون تغليف

    وكان اسم المنتج لا يذكر هذه الحالة صراحة،
    فلا تفترض وجودها.

12. إذا كانت السياسة تقول مثلاً:
    "العطور المفتوحة غير قابلة للاسترجاع"
    واسم المنتج فقط "عطر"،
    فلا تعتبره مفتوحاً.

13. إذا لم تستطع تحديد مدة الاسترجاع
    التي تنطبق على المنتج بثقة:
    return_days = "لم يُذكر"

14. إذا لم تستطع تحديد مدة الاستبدال
    التي تنطبق على المنتج بثقة:
    exchange_days = "لم يُذكر"

15. إذا كانت السياسة تنص صراحة على عدم وجود
    استرجاع أو استبدال بشكل عام،
    فلا تحول ذلك إلى عدد أيام.
    استخدم:
    "غير متاح"

16. لا تخلط بين:
    - الاسترجاع
    - الاستبدال
    - الضمان
    - الشحن
    - التعويض
    - الإلغاء

    استخرج فقط مدة الاسترجاع
    ومدة الاستبدال.

==================================================
أمثلة توضيحية
==================================================

مثال 1:

المنتج:
عطر

السياسة:
يمكن استرجاع المنتجات خلال X يومًا،
ما عدا العطور المفتوحة.

النتيجة الصحيحة:
return_days = "X يوم"

لأن اسم المنتج لا يقول إنه مفتوح.

--------------------------------------------------

مثال 2:

المنتج:
عطر مفتوح

السياسة:
يمكن استرجاع المنتجات خلال X يومًا،
ما عدا العطور المفتوحة.

النتيجة الصحيحة:
return_days = "غير متاح — المنتج مستثنى"

--------------------------------------------------

مثال 3:

المنتج:
ملابس داخلية

السياسة:
جميع المنتجات قابلة للاسترجاع خلال X يومًا،
باستثناء الملابس الداخلية.

النتيجة الصحيحة:
return_days = "غير متاح — المنتج مستثنى"

--------------------------------------------------

مثال 4:

المنتج:
حذاء

السياسة:
جميع المنتجات قابلة للاسترجاع خلال X يومًا،
باستثناء الملابس الداخلية.

النتيجة الصحيحة:
return_days = "X يوم"

--------------------------------------------------

مثال 5:

المنتج:
ساعة

السياسة:
الإكسسوارات تسترجع خلال A.
الساعات تسترجع خلال B.
الفساتين تسترجع خلال C.

النتيجة الصحيحة:
return_days = "B"

لا تستخدم A أو C لأنهما لفئات أخرى.

--------------------------------------------------

مثال 6:

المنتج:
خلخال

السياسة:
الإكسسوارات تسترجع خلال A.
الساعات تسترجع خلال B.

النتيجة الصحيحة:
return_days = "A"

لأن الخلخال من الإكسسوارات.

==================================================
قاعدة الأولوية
==================================================

ترتيب الأولوية:

1. سياسة خاصة بالمنتج نفسه.
2. سياسة خاصة بفئة المنتج.
3. السياسة العامة.
4. إذا لم توجد معلومة تنطبق بثقة:
   "لم يُذكر"

لا تستخدم سياسة فئة أخرى
لمجرد أنها تحتوي على مدة واضحة.

==================================================
OUTPUT
==================================================

أرجع JSON فقط.

يجب أن يحتوي على حقلين فقط:

{{
    "return_days": "...",
    "exchange_days": "..."
}}

لا تضف أي حقول أخرى.

لا تضف:
- explanation
- highlights
- excluded
- excluded_items
- free_returns

القيم يجب أن تكون جاهزة للعرض للمستخدم.

أمثلة للقيم المقبولة:

"3 أيام"
"24 ساعة"
"لم يُذكر"
"غير متاح"
"غير متاح — المنتج مستثنى"

لا تضف أي نص خارج JSON.
"""

    response = model.invoke(prompt)

    content = response.content.strip()

    # =================================================
    # REMOVE MARKDOWN
    # =================================================

    content = re.sub(
        r"^```json\s*",
        "",
        content,
        flags=re.IGNORECASE
    )

    content = re.sub(
        r"^```\s*",
        "",
        content
    )

    content = re.sub(
        r"\s*```$",
        "",
        content
    )

    content = content.strip()

    # =================================================
    # PARSE JSON
    # =================================================

    try:

        result = json.loads(content)

    except json.JSONDecodeError:

        return {
            "result": {
                "error": "AI returned invalid JSON",
                "raw_response": content
            }
        }

    # =================================================
    # RETURN ONLY REQUIRED FIELDS
    # =================================================

    result = {
        "return_days": result.get(
            "return_days",
            "لم يُذكر"
        ),

        "exchange_days": result.get(
            "exchange_days",
            "لم يُذكر"
        )
    }

    return {
        "result": result
    }


# =====================================================
# LANGGRAPH
# =====================================================

graph = StateGraph(PolicyState)

graph.add_node(
    "analyze_policy",
    analyze_policy
)

graph.add_edge(
    START,
    "analyze_policy"
)

graph.add_edge(
    "analyze_policy",
    END
)

app = graph.compile()


# =====================================================
# PUBLIC FUNCTION
# =====================================================
#
# هذه هي الدالة التي سيستخدمها الـ Backend لاحقاً.
#
# مثال:
#
# result = analyze_product_policy(
#     "عطر",
#     "يمكن استرجاع المنتجات خلال 14 يوم..."
# )
#
# =====================================================

def analyze_product_policy(
    product_name: str,
    policy_text: str
) -> dict:

    state = {

        "product_name":
            product_name,

        "policy_text":
            policy_text,

        "result":
            {}
    }

    result = app.invoke(
        state
    )

    return result["result"]


# =====================================================
# LOCAL TEST
# =====================================================

if __name__ == "__main__":

    print("=" * 60)
    print("🧪 Wudhoh Policy Agent")
    print("=" * 60)

    test_product = "عطر"

    test_policy = """
    يمكن استرجاع المنتجات خلال 14 يومًا
    من تاريخ الشراء، ما عدا العطور المفتوحة
    ومستحضرات التجميل المستخدمة.

    الاستبدال متاح خلال 7 أيام.
    """

    print("\n🛍️ Product:")
    print(test_product)

    print("\n📄 Policy:")
    print(test_policy)

    result = analyze_product_policy(
        test_product,
        test_policy
    )

    print("\n🤖 Agent result:")

    print(
        json.dumps(
            result,
            ensure_ascii=False,
            indent=2
        )
    )